import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../dist/', import.meta.url));
const output = path.join(root, 'precache.js');
const assets = (await readdir(root, { recursive: true }))
  .map((name) => name.replaceAll('\\', '/'))
  .filter(
    (name) => /\.(?:js|css|html|webmanifest|svg|png|gz|txt)$/.test(name) && name !== 'precache.js',
  )
  .sort();
const hash = createHash('sha256');
for (const name of assets) {
  const bytes = await readFile(path.join(root, name));
  // Git can check text out as CRLF on Windows and LF on the Linux publisher.
  // Cache revisions must describe the same source on both platforms.
  hash
    .update(name)
    .update('\0')
    .update(/\.(?:png|gz)$/.test(name) ? bytes : bytes.toString('utf8').replace(/\r\n/g, '\n'));
}
const manifest = {
  revision: hash.digest('hex').slice(0, 16),
  files: [
    './',
    ...assets.filter((name) => name !== 'sw.js').map((name) => './' + name),
    './precache.js',
  ],
};
const source = `// Generated by npm run precache. Do not edit.\nself.PIXEL_PRECACHE = ${JSON.stringify(manifest, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8').catch(() => '')).replace(/\r\n/g, '\n') !== source) {
    console.error('离线资源清单已过期，请运行 npm run precache。');
    process.exitCode = 1;
  }
} else await writeFile(output, source);
